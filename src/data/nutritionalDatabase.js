// Helper: retorna planilha + cardápio para um array de perfis
export function getNutritionalPlanForProfiles(profiles = []) {
  const planilhas = profiles.map(pid => PLANILHAS_NUTRICIONAIS[pid]).filter(Boolean);
  const cardapios = profiles.map(pid => CARDAPIOS[pid]).filter(Boolean);
  const receitas = profiles.flatMap(pid => RECEITAS_FUNCIONAIS[pid] || []);
  return { planilhas, cardapios, receitas };
}
